fun main() {
    // operators

    var i=10

    var j=11

    println( i + j)

    println( i - j)

    println( i * j)

    println( i % j)

    println( i / j)

    // Relational Operators

    println( i > j)

    println( i < j)

    println( i <= j)

    println( i >= j)

    println( i == j)

    println( i != j)

    // Increment and decrement Operators

    println( i++ + ++j)

    // Decreament Operators

    println( i-- + --j)

}